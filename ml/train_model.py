"""Train the landslide hazard model.

    python ml/train_model.py                    # 24 000 rows, auto backend
    python ml/train_model.py --rows 60000        # regenerate a larger set
    python ml/train_model.py --backend numpy     # force the dependency-free one

What it produces
----------------
`ml/model.pkl` holds a bagged ensemble plus everything needed to serve and
audit it: the feature contract, the chosen backend, evaluation metrics, a
calibration table, and the training-data summary. `ml/model_card.json` is the
same metadata in readable form for the docs and the /api/model endpoint.

Backend selection is deliberate, not accidental
-----------------------------------------------
XGBoost is preferred, scikit-learn is next, and `ml/fallback_gbm.NumpyGBM`
(same Newton boosting, NumPy only) is last. All three are trained and scored by
identical code, so a laptop where `pip install xgboost` fails still gets a real
gradient-boosted model with real metrics rather than a stub - and the report
says which backend produced it.

Honest labelling
----------------
The training rows are SYNTHETIC, generated by the documented physical model in
`ml/physics.py`. Metrics below describe how well the model recovers that
process from noisy samples of it. They are not evidence of real-world landslide
forecast skill, and the model card records this in `data_provenance`.
"""
