LIMITATIONS = [
    "Trained on simulated data, so it reproduces a physical model rather than the observed landslide record.",
    "Hourly resolution and regional terrain averages - it cannot resolve an individual slope or a specific building.",
    "No earthquake, reservoir drawdown, blasting or excavation triggers are represented.",
    "Rainfall beyond the training range is clipped at the documented BOUNDS, so extreme what-if answers saturate rather than extrapolate.",
    "Decision support only: it does not replace inspection by a qualified geotechnical engineer.",
]


def _load_frame(
    path: Path, rows: int, seed: int, regenerate: bool, say: Callable[[str], None]
) -> pd.DataFrame:
    """Load the training CSV, generating it first if it is missing or too small."""
    frame: pd.DataFrame | None = None
    if path.exists() and not regenerate:
        frame = pd.read_csv(path)
        say(f"  data           {path} ({len(frame):,} rows)")
        if len(frame) < rows:
            say(f"  regenerating   have {len(frame):,} rows, need {rows:,}")
            frame = None
    if frame is None:
        from ml.data.generate_dataset import generate

        say(f"  generating     {rows:,} synthetic rows (seed {seed})")
        frame = generate(rows=rows, seed=seed)
        path.parent.mkdir(parents=True, exist_ok=True)
        frame.to_csv(path, index=False)
        say(f"  wrote          {path}")
    return frame.iloc[:rows].reset_index(drop=True) if len(frame) > rows else frame


def train(
    *,
    rows: int = 24_000,
    data_path: Path = DEFAULT_DATA,
    backend: str = "auto",
    members: int = 5,
    seed: int = 20260902,
    regenerate: bool = False,
    verbose: bool = True,
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Fit the bagged ensemble; return the servable bundle and the model card."""

    def say(message: str) -> None:
        if verbose:
            print(message, flush=True)

    say("training landslide hazard model")
    frame = _load_frame(data_path, rows, seed, regenerate, say)
    X = frame_to_matrix(frame)
    y = labels(frame)
    groups = frame[GROUP_COLUMN].to_numpy()
    train_idx, val_idx, test_idx = group_split(groups)

    say(f"  rows           {X.shape[0]:,} | positives {int(y.sum()):,} ({100 * y.mean():.2f}%)")
    say(
        f"  grouped split  train {train_idx.size:,} / val {val_idx.size:,} / "
        f"test {test_idx.size:,} (no region in two splits)"
    )

    name, factory = resolve_backend(backend)
    say(f"  backend        {name}")

    # Bootstrap resample per member. This is real bagging, and for backends
    # without row subsampling of their own it is the only source of member
    # diversity - without it the "ensemble" would be five identical models and
    # the confidence derived from their spread would be meaningless.
    rng = np.random.default_rng(seed)
    fitted: list[Any] = []
    started = time.time()
    n_members = max(1, int(members))
    for member in range(n_members):
        picks = rng.integers(0, train_idx.size, size=train_idx.size)
        idx = train_idx[picks]
        model = factory(seed + 101 * member)
        model.fit(X[idx], y[idx])
        fitted.append(model)
        say(f"    member {member + 1}/{n_members} fitted ({time.time() - started:.1f}s elapsed)")
    elapsed = time.time() - started

    p_test = ensemble_proba(fitted, X[test_idx])
    spread = ensemble_spread(fitted, X[test_idx])

    metrics = {
        "train": evaluate(y[train_idx], ensemble_proba(fitted, X[train_idx])),
        "validation": evaluate(y[val_idx], ensemble_proba(fitted, X[val_idx])),
        "test": evaluate(y[test_idx], p_test),
    }
    imp_method, importance = importance_table(fitted, X[val_idx], y[val_idx])

    # The labels are Bernoulli draws, so even the generating probability cannot
    # score a perfect AUC against them. Measuring that limit is the only honest
    # way to say whether 0.83 is a good number or a poor one.
    ceiling: dict[str, Any] | None = None
    if "hazard_probability_true" in frame.columns:
        truth = frame["hazard_probability_true"].to_numpy(dtype=float)
        limit = roc_auc(y[test_idx], truth[test_idx])
        ceiling = {
            "note": (
                "ROC AUC of the generating probability itself against the sampled "
                "labels - the irreducible ceiling for any model of this data."
            ),
            "test_roc_auc": round(limit, 4),
            "model_fraction_of_ceiling": round(float(metrics["test"]["roc_auc"] / limit), 4),
            "correlation_with_true_probability": round(
                float(np.corrcoef(p_test, truth[test_idx])[0, 1]), 4
            ),
        }

    bundle: dict[str, Any] = {
        "format": "landslide-ensemble/1",
        "model_name": MODEL_NAME,
        "model_version": MODEL_VERSION,
        "feature_schema_version": FEATURE_SCHEMA_VERSION,
        "feature_order": list(FEATURE_ORDER),
        "backend": name,
        "member_format": "numpy-gbm-dict" if isinstance(fitted[0], NumpyGBM) else "estimator",
        "members": [m.to_dict() if isinstance(m, NumpyGBM) else m for m in fitted],
        "hyperparams": dict(HYPERPARAMS),
        "trained_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "training_seconds": round(elapsed, 2),
        "training_rows": int(X.shape[0]),
        "split_sizes": {
            "train": int(train_idx.size),
            "validation": int(val_idx.size),
            "test": int(test_idx.size),
        },
        "regions": {
            "total": int(np.unique(groups).size),
            "train": int(np.unique(groups[train_idx]).size),
            "validation": int(np.unique(groups[val_idx]).size),
            "test": int(np.unique(groups[test_idx]).size),
        },
        "metrics": metrics,
        "label_noise_ceiling": ceiling,
        "importance_method": imp_method,
        "feature_importance": importance,
        "band_distribution": band_distribution(p_test),
        "confidence_reference": {
            "note": (
                "Member disagreement in log-odds on held-out rows; predict.py scales "
                "the reported confidence against spread_p90."
            ),
            "spread_p50": round(float(np.percentile(spread, 50)), 4),
            "spread_p90": round(float(np.percentile(spread, 90)), 4),
            "spread_max": round(float(spread.max()), 4),
        },
        "training_summary": summarise(X[train_idx]),
        "data_provenance": dict(PROVENANCE),
        "intended_use": (
            "Screening and triage of landslide hazard across monitored regions, "
            "and interactive what-if exploration. Decision support only."
        ),
        "limitations": list(LIMITATIONS),
    }
    card = {key: value for key, value in bundle.items() if key != "members"}
    card["members"] = n_members
    return bundle, card


def main() -> int:
    parser = argparse.ArgumentParser(description="Train the landslide hazard model")
    parser.add_argument("--rows", type=int, default=24_000, help="training rows to use")
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA)
    parser.add_argument("--out", type=Path, default=DEFAULT_MODEL)
    parser.add_argument("--card", type=Path, default=DEFAULT_CARD)
    parser.add_argument(
        "--backend",
        choices=["auto", "xgboost", "sklearn", "numpy"],
        default="auto",
        help="auto prefers xgboost, then scikit-learn, then the bundled NumPy GBM",
    )
    parser.add_argument("--members", type=int, default=5, help="bagged ensemble size")
    parser.add_argument("--seed", type=int, default=20260902)
    parser.add_argument("--regenerate", action="store_true", help="rebuild the CSV even if present")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    bundle, card = train(
        rows=args.rows,
        data_path=args.data,
        backend=args.backend,
        members=args.members,
        seed=args.seed,
        regenerate=args.regenerate,
        verbose=not args.quiet,
    )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("wb") as handle:
        pickle.dump(bundle, handle, protocol=pickle.HIGHEST_PROTOCOL)
    args.card.write_text(json.dumps(card, indent=2), encoding="utf-8")

    if args.quiet:
        return 0

    test = card["metrics"]["test"]
    bands = card["band_distribution"]
    print(f"\nsaved model    {args.out}  ({args.out.stat().st_size / 1024:.0f} KB)")
    print(f"saved card     {args.card}")
    print("\nheld-out regions the model never saw")
    print(f"  ROC AUC      {test['roc_auc']:.4f}")
    print(f"  PR AUC       {test['pr_auc']:.4f}   (positive rate {test['positive_rate']:.4f})")
    print(f"  Brier        {test['brier']:.4f}")
    print(f"  calibration  ECE {test['ece']:.4f}")
    if card["label_noise_ceiling"]:
        ceiling = card["label_noise_ceiling"]
        print(
            f"  noise limit  {ceiling['test_roc_auc']:.4f} -> model reaches "
            f"{100 * ceiling['model_fraction_of_ceiling']:.1f}% of what is achievable"
        )
    print(f"\nscore range    {bands['score_min']:.1f} - {bands['score_max']:.1f}")
    print("  " + "  ".join(f"{b} {bands['percent'][b]:.1f}%" for b in BAND_ORDER))
    print(f"\ntop drivers ({card['importance_method']})")
    for row in card["feature_importance"][:6]:
        print(f"  {row['feature']:<28} {100 * row['importance']:5.1f}%   {row['group']}")
    print(
        "\nSYNTHETIC TRAINING DATA. These metrics describe how well the model "
        "recovers\nml/physics.py - they are not real-world landslide forecast skill."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())






