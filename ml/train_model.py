# Shared across backends so the comparison is like-for-like. Depth is modest
# and min_child_weight high because grouped validation showed deeper trees
# memorising individual regions without improving unseen-region AUC.
HYPERPARAMS = {
    "n_estimators": 300,
    "learning_rate": 0.09,
    "max_depth": 4,
    "min_child_weight": 12.0,
    "reg_lambda": 2.0,
    "subsample": 0.85,
    "colsample_bytree": 0.9,
}


def _xgboost_factory() -> Callable[[int], Any] | None:
    try:
        from xgboost import XGBClassifier
    except Exception:
        return None

    def make(seed: int) -> Any:
        return XGBClassifier(
            n_estimators=HYPERPARAMS["n_estimators"],
            learning_rate=HYPERPARAMS["learning_rate"],
            max_depth=HYPERPARAMS["max_depth"],
            min_child_weight=HYPERPARAMS["min_child_weight"],
            reg_lambda=HYPERPARAMS["reg_lambda"],
            subsample=HYPERPARAMS["subsample"],
            colsample_bytree=HYPERPARAMS["colsample_bytree"],
            objective="binary:logistic",
            eval_metric="logloss",
            tree_method="hist",
            random_state=seed,
            n_jobs=0,
            verbosity=0,
        )

    return make


def _sklearn_factory() -> Callable[[int], Any] | None:
    try:
        from sklearn.ensemble import HistGradientBoostingClassifier
    except Exception:
        return None

    def make(seed: int) -> Any:
        return HistGradientBoostingClassifier(
            max_iter=HYPERPARAMS["n_estimators"],
            learning_rate=HYPERPARAMS["learning_rate"],
            max_depth=HYPERPARAMS["max_depth"] + 1,
            min_samples_leaf=40,
            l2_regularization=HYPERPARAMS["reg_lambda"],
            max_bins=64,
            early_stopping=False,
            random_state=seed,
        )

    return make


def _numpy_factory() -> Callable[[int], Any]:
    def make(seed: int) -> Any:
        return NumpyGBM(
            n_estimators=HYPERPARAMS["n_estimators"],
            learning_rate=HYPERPARAMS["learning_rate"],
            max_depth=HYPERPARAMS["max_depth"],
            min_child_weight=HYPERPARAMS["min_child_weight"],
            reg_lambda=HYPERPARAMS["reg_lambda"],
            subsample=HYPERPARAMS["subsample"],
            colsample_bytree=HYPERPARAMS["colsample_bytree"],
            random_state=seed,
        )

    return make


def resolve_backend(preferred: str = "auto") -> tuple[str, Callable[[int], Any]]:
    """Pick the best available backend, honouring an explicit request."""
    options: list[tuple[str, Callable[[], Callable[[int], Any] | None]]] = [
        ("xgboost", _xgboost_factory),
        ("sklearn", _sklearn_factory),
        ("numpy", lambda: _numpy_factory()),
    ]
    if preferred != "auto":
        for name, loader in options:
            if name == preferred:
                factory = loader()
                if factory is None:
                    raise SystemExit(f"backend '{preferred}' requested but not installed")
                return name, factory
        raise SystemExit(f"unknown backend '{preferred}'")
    for name, loader in options:
        factory = loader()
        if factory is not None:
            return name, factory
    raise SystemExit("no usable backend")  # pragma: no cover - numpy is required


# --------------------------------------------------------------------- metrics
# Written out in NumPy rather than imported from scikit-learn, because the whole
# point of the fallback backend is that the pipeline still runs and still
# reports honest numbers when scikit-learn is not installed.

def roc_auc(y: np.ndarray, p: np.ndarray) -> float:
    """Rank-based AUC (Mann-Whitney U), tie-corrected via average ranks."""
    y = np.asarray(y).ravel()
    positives = int(y.sum())
    negatives = y.size - positives
    if positives == 0 or negatives == 0:
        return float("nan")
    order = np.argsort(p, kind="mergesort")
    ranks = np.empty(p.size, dtype=float)
    ranks[order] = np.arange(1, p.size + 1, dtype=float)
    sorted_p = p[order]
    start = 0
    while start < sorted_p.size:
        stop = start + 1
        while stop < sorted_p.size and sorted_p[stop] == sorted_p[start]:
            stop += 1
        if stop - start > 1:
            ranks[order[start:stop]] = ranks[order[start:stop]].mean()
        start = stop
    return float((ranks[y == 1].sum() - positives * (positives + 1) / 2.0) / (negatives * positives))


def average_precision(y: np.ndarray, p: np.ndarray) -> float:
    """Area under the precision-recall curve - the metric that matters when
    only ~11% of rows are positive and ranking the rare events is the job."""
    y = np.asarray(y).ravel()
    if y.sum() == 0:
        return float("nan")
    order = np.argsort(-p, kind="mergesort")
    hits = np.cumsum(y[order])
    precision = hits / np.arange(1, y.size + 1)
    return float((precision * y[order]).sum() / y.sum())


def brier(y: np.ndarray, p: np.ndarray) -> float:
    return float(np.mean((p - np.asarray(y).ravel()) ** 2))


def log_loss(y: np.ndarray, p: np.ndarray) -> float:
    q = np.clip(p, 1e-9, 1 - 1e-9)
    y = np.asarray(y).ravel()
    return float(-np.mean(y * np.log(q) + (1 - y) * np.log(1 - q)))


def calibration_table(y: np.ndarray, p: np.ndarray, bins: int = 10) -> list[dict[str, float]]:
    """Predicted vs observed frequency per decile of predicted risk.

    This is the table to read before trusting a risk *score*: AUC only says the
    ordering is right, calibration says a score of 70 really does correspond to
    roughly a 70% chance in the modelled world.
    """
    y = np.asarray(y).ravel()
    edges = np.linspace(0.0, 1.0, bins + 1)
    rows: list[dict[str, float]] = []
    for i in range(bins):
        low, high = edges[i], edges[i + 1]
        mask = (p >= low) & (p < high if i < bins - 1 else p <= high)
        if not mask.any():
            continue
        rows.append(
            {
                "bin_low": round(float(low), 3),
                "bin_high": round(float(high), 3),
                "count": int(mask.sum()),
                "mean_predicted": round(float(p[mask].mean()), 4),
                "observed_rate": round(float(y[mask].mean()), 4),
            }
        )
    return rows


def expected_calibration_error(rows: list[dict[str, float]], total: int) -> float:
    if total == 0:
        return float("nan")
    return float(
        sum(r["count"] * abs(r["mean_predicted"] - r["observed_rate"]) for r in rows) / total
    )


def evaluate(y: np.ndarray, p: np.ndarray) -> dict[str, Any]:
    table = calibration_table(y, p)
    return {
        "n": int(np.asarray(y).size),
        "positive_rate": round(float(np.mean(y)), 4),
        "roc_auc": round(roc_auc(y, p), 4),
        "pr_auc": round(average_precision(y, p), 4),
        "brier": round(brier(y, p), 4),
        "log_loss": round(log_loss(y, p), 4),
        "mean_predicted": round(float(p.mean()), 4),
        "ece": round(expected_calibration_error(table, int(np.asarray(y).size)), 4),
        "calibration": table,
    }


# -------------------------------------------------------------------- ensemble

def _proba(model: Any, X: np.ndarray) -> np.ndarray:
    """Positive-class probability, whichever backend produced the model."""
    return np.asarray(model.predict_proba(X), dtype=float)[:, 1]


def ensemble_proba(models: Sequence[Any], X: np.ndarray) -> np.ndarray:
    return np.mean([_proba(m, X) for m in models], axis=0)


def logit(p: np.ndarray) -> np.ndarray:
    q = np.clip(np.asarray(p, dtype=float), 1e-6, 1.0 - 1e-6)
    return np.log(q / (1.0 - q))


def ensemble_spread(models: Sequence[Any], X: np.ndarray) -> np.ndarray:
    """Disagreement between members, measured in log-odds.

    A wide spread means the members saw different bootstrap samples and reached
    different conclusions, which is exactly the signal `predict.py` turns into
    the reported confidence - rather than printing a number that looks like
    certainty but was never measured.

    Log-odds rather than probability, because probability spread shrinks
    automatically near 0 and 1: two members at 0.001 and 0.02 differ by a
    factor of twenty but only 0.019 in probability. Comparing that against a
    reference dominated by low-risk rows would report false certainty on
    exactly the rows an officer cares about.
    """
    if len(models) < 2:
        return np.zeros(X.shape[0], dtype=float)
    return np.std([logit(_proba(m, X)) for m in models], axis=0)


def _permutation_importance(
    models: Sequence[Any], X: np.ndarray, y: np.ndarray, *, seed: int = 17
) -> np.ndarray:
    """AUC lost when one column is shuffled.

    Needed because scikit-learn's HistGradientBoostingClassifier exposes no
    native importances, and the explainability panel must work on every backend.
    """
    rng = np.random.default_rng(seed)
    base = roc_auc(y, ensemble_proba(models, X))
    drops = np.zeros(X.shape[1], dtype=float)
    for i in range(X.shape[1]):
        shuffled = np.array(X, copy=True)
        shuffled[:, i] = shuffled[rng.permutation(X.shape[0]), i]
        drops[i] = max(0.0, base - roc_auc(y, ensemble_proba(models, shuffled)))
    return drops


def importance_table(
    models: Sequence[Any], X: np.ndarray, y: np.ndarray
) -> tuple[str, list[dict[str, Any]]]:
    """Per-feature importance shares, plus the method that produced them."""
    vectors = [
        np.asarray(m.feature_importances_, dtype=float)
        for m in models
        if hasattr(m, "feature_importances_")
    ]
    if vectors:
        totals = np.mean(vectors, axis=0)
        method = "split-gain"
    else:
        totals = _permutation_importance(models, X, y)
        method = "permutation-auc-drop"
    total = float(totals.sum())
    shares = totals / total if total > 0 else np.full(totals.size, 1.0 / totals.size)
    return method, [
        {
            "feature": FEATURE_ORDER[i],
            "group": FACTOR_GROUPS[FEATURE_ORDER[i]],
            "importance": round(float(shares[i]), 4),
        }
        for i in np.argsort(-shares)
    ]


def band_distribution(p: np.ndarray) -> dict[str, Any]:
    """Where predicted scores land across the five specified risk bands.

    Recorded so the demo cannot be accused of a model that never leaves one
    band: the card shows CRITICAL is reachable and how often it is reached.
    """
    scores = 100.0 * np.asarray(p, dtype=float)
    counts = {band: 0 for band in BAND_ORDER}
    for s in scores:
        counts[risk_level(float(s))] += 1
    total = max(1, int(scores.size))
    return {
        "counts": counts,
        "percent": {b: round(100.0 * c / total, 2) for b, c in counts.items()},
        "score_min": round(float(scores.min()), 2),
        "score_p50": round(float(np.percentile(scores, 50)), 2),
        "score_p95": round(float(np.percentile(scores, 95)), 2),
        "score_max": round(float(scores.max()), 2),
    }


